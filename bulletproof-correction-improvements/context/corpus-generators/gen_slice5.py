def period_variant(s: str) -> str | None:
    if s.endswith("."):
        return s[:-1]
    if s and (s[-1].isalnum() or s[-1] in "`)"):
        return s + "."
    return None


def fix(inp, fixed, errors, preserve, tags, extra=()):
    outs = [fixed, *extra]
    pv = period_variant(fixed)
    if pv and pv not in outs:
        outs.append(pv)
    return {
        "input": inp,
        "expected": {"kind": "fix", "acceptableOutputs": outs[:4]},
        "errors": errors,
        "mustPreserve": preserve,
        "tags": tags,
    }


def clean(inp, preserve, tags):
    return {
        "input": inp,
        "expected": {"kind": "unchanged"},
        "errors": [],
        "mustPreserve": preserve,
        "tags": ["clean", *tags],
    }


